#!/usr/bin/env python3
"""
Canary SRS — Reproducible Detection Engine Evaluation CLI (FR-44)
Measures empirical True Positive Rate (TPR) and False Positive Rate (FPR) with Wilson score confidence intervals.
Outputs: data/accuracy/latest_evaluation.json
"""

import json
import logging
import os
import sys
from datetime import UTC, datetime
from typing import Any

# Ensure backend modules are on path
sys.path.insert(
    0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "backend"))
)

from app.checks.duplicates import run_duplicate_check_for_task
from app.checks.marker import detect_marker_in_text
from app.checks.speed import run_speed_check
from app.services.calibration import wilson_score_interval

logging.basicConfig(
    level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s"
)
logger = logging.getLogger("canary-eval")

OUTPUT_PATH = os.path.abspath(
    os.path.join(
        os.path.dirname(__file__), "..", "data", "accuracy", "latest_evaluation.json"
    )
)


def build_evaluation_benchmark() -> list[dict[str, Any]]:
    """
    Constructs a controlled benchmark dataset containing known contaminated
    answers (ground_truth=True) and clean human answers (ground_truth=False).
    """
    records = []

    # 1. Clean human negative controls (N=40 clean answers)
    clean_prompts = [
        "Explain how a refrigerator keeps food cold.",
        "Describe the rules of tennis.",
        "What causes ocean tides on Earth?",
        "How do trees survive winter weather?",
    ]
    clean_answers = [
        "Refrigerators use a compressor cycle to vaporize and condense refrigerant, absorbing heat from the interior.",
        "Tennis is played on a rectangular court where players hit a felt ball over a net within boundary lines.",
        "Ocean tides are predominantly generated by the gravitational pull of the moon and sun acting upon Earth's oceans.",
        "Deciduous trees shed foliage to conserve moisture, while conifers utilize thick waxy needles and natural resin antifreezes.",
    ]
    for p_idx, prompt in enumerate(clean_prompts):
        for w_idx in range(10):
            records.append(
                {
                    "id": f"ans_clean_{p_idx}_{w_idx}",
                    "task_id": f"clean_task_{p_idx}",
                    "worker_id": f"human_worker_{p_idx}_{w_idx}",
                    "prompt": prompt,
                    "answer": f"{clean_answers[p_idx]} (Observation note {w_idx} from annotator perspective).",
                    "seconds_spent": 45.0 + (w_idx * 5.0),
                    "ground_truth_contaminated": False,
                    "expected_marker": None,
                }
            )

    # 2. Injected marker leak positives (N=15)
    for i in range(15):
        marker = f"cnry_eval{i:04d}"
        records.append(
            {
                "id": f"ans_marker_{i}",
                "task_id": f"marker_task_{i}",
                "worker_id": f"marker_worker_{i}",
                "prompt": f"Write an overview of architecture concept {i}.",
                "answer": f"Here is the requested architectural concept {marker} analysis with design details.",
                "seconds_spent": 30.0,
                "ground_truth_contaminated": True,
                "expected_marker": marker,
            }
        )

    # 3. Model reference near-duplicates / cross-worker duplicates (N=15)
    ref_template = "The theoretical framework establishes asymptotic convergence guarantees under Lipschitz continuous gradients."
    for i in range(15):
        records.append(
            {
                "id": f"ans_dup_{i}",
                "task_id": "dup_task_shared",
                "worker_id": f"dup_worker_{i}",
                "prompt": "Explain gradient convergence.",
                "answer": f"{ref_template} Additional minor variation suffix {i % 3}.",
                "seconds_spent": 3.0
                if i % 2 == 0
                else 25.0,  # Fast velocity trigger for half
                "ground_truth_contaminated": True,
                "expected_marker": None,
            }
        )

    return records


def run_evaluation() -> dict[str, Any]:
    benchmark = build_evaluation_benchmark()
    logger.info("Loaded benchmark dataset with %d total samples", len(benchmark))

    tp = 0
    fp = 0
    tn = 0
    fn = 0

    # Group by task for task-level checks
    by_task: dict[str, list[dict[str, Any]]] = {}
    for item in benchmark:
        by_task.setdefault(item["task_id"], []).append(item)

    flagged_workers = set()

    for item in benchmark:
        worker_flagged = False

        # 1. Marker check
        if item.get("expected_marker"):
            hit = detect_marker_in_text(item["answer"], item["expected_marker"])
            if hit:
                worker_flagged = True

        # 2. Speed check
        speed_hit = run_speed_check(
            {
                "task_id": item["task_id"],
                "worker_id": item["worker_id"],
                "answer": item["answer"],
                "seconds_spent": item.get("seconds_spent"),
            }
        )
        if speed_hit:
            worker_flagged = True

        # 3. Task-level duplicate & similarity checks
        task_group = by_task[item["task_id"]]
        if len(task_group) > 1:
            dup_findings = run_duplicate_check_for_task(item["task_id"], task_group)
            if any(f.worker_id == item["worker_id"] for f in dup_findings):
                worker_flagged = True

        if worker_flagged:
            flagged_workers.add(item["worker_id"])

        # Compare against ground truth
        is_contaminated = item["ground_truth_contaminated"]
        if is_contaminated and worker_flagged:
            tp += 1
        elif not is_contaminated and worker_flagged:
            fp += 1
        elif not is_contaminated and not worker_flagged:
            tn += 1
        else:
            fn += 1

    total_positives = tp + fn
    total_negatives = tn + fp
    sample_size = len(benchmark)

    tpr = round(tp / total_positives, 4) if total_positives > 0 else 0.0
    fpr = round(fp / total_negatives, 4) if total_negatives > 0 else 0.0

    tpr_lower, tpr_upper = wilson_score_interval(tp, total_positives)
    fpr_lower, fpr_upper = wilson_score_interval(fp, total_negatives)

    results = {
        "dataset_version": "canary-synthetic-benchmark-v1.0",
        "evaluated_at": datetime.now(UTC).isoformat(),
        "sample_size": sample_size,
        "confusion_matrix": {
            "true_positives": tp,
            "false_positives": fp,
            "true_negatives": tn,
            "false_negatives": fn,
        },
        "metrics": {
            "tpr": tpr,
            "fpr": fpr,
            "tpr_ci_lower": tpr_lower,
            "tpr_ci_upper": tpr_upper,
            "fpr_ci_lower": fpr_lower,
            "fpr_ci_upper": fpr_upper,
            "ci_method": "wilson",
            "confidence_level": 0.95,
        },
        "checks_tested": ["marker", "similarity", "duplicates", "speed"],
        "reproduction_command": "uv run python scripts/evaluate.py",
        "notice": (
            "Empirical evaluation results generated under reproducible benchmark conditions. "
            "Findings serve as human-review evidence and are subject to Wilson confidence bounds."
        ),
    }

    # Save artifact
    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        json.dump(results, f, indent=2)

    logger.info("Saved evaluation results to %s", OUTPUT_PATH)
    logger.info(
        "Evaluation summary: TPR=%.2f%% [95%% CI: %.2f%% - %.2f%%], FPR=%.2f%% [95%% CI: %.2f%% - %.2f%%]",
        tpr * 100.0,
        tpr_lower * 100.0,
        tpr_upper * 100.0,
        fpr * 100.0,
        fpr_lower * 100.0,
        fpr_upper * 100.0,
    )
    return results


if __name__ == "__main__":
    run_evaluation()
